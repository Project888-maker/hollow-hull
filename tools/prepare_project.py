"""Patch the HollowHull Unreal project so the Hollow Hull scripts can build into it.

The project itself must be created with Epic's launcher (New Project > Games >
Third Person > Blueprint): Unreal 5.7 templates pull in shared content packs
(input actions, mannequin) that only the launcher installs.

    python prepare_project.py --existing "C:/Projects/HollowHull/HollowHull.uproject" --repo "<hollow-hull folder>"

It enables the Python and Editor Scripting plugins, makes L_FloodedDeck the
startup map, and writes Content/Python/init_unreal.py. Unreal runs that file on
every editor start; it builds the level only when run_phase1.ps1 has left a
build request, so normal editor launches are untouched and the editor stays open.
Plain Python 3, no Unreal needed.
"""

import argparse
import json
import os
import re
import sys

PLUGINS = ["PythonScriptPlugin", "EditorScriptingUtilities"]
MAP = "/Game/HollowHull/Maps/L_FloodedDeck.L_FloodedDeck"

INIT_UNREAL = '''# Generated by hollow-hull tools/prepare_project.py - safe to delete.
# Builds the levels when run_phase1.ps1 leaves Saved/HollowHull/build_request,
# and starts the play recorder, the game's sound and the world events.
import os
import runpy

import unreal

HH_REPO = r"{repo}"
_saved = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir())
_request = os.path.join(_saved, "HollowHull", "build_request")

# play recorder: notes what the characters do while you play (reports/phase1/play_trace.json)
try:
    import sys
    sys.path.insert(0, os.path.join(HH_REPO, "unreal"))
    import hh_trace
    hh_trace.start(os.path.join(HH_REPO, "reports", "phase1", "play_trace.json"))
except Exception as exc:
    unreal.log_warning("[HH] play recorder not started: " + str(exc))

# sound: footsteps, swings, hits, deaths and the level's music while you play
try:
    import hh_audio
    hh_audio.start(os.path.join(HH_REPO, "reports", "phase1", "audio_trace.json"))
except Exception as exc:
    unreal.log_warning("[HH] sound not started: " + str(exc))

# world events: the fall into The Hollow when Sevarog dies, and the cave's heartbeat
try:
    import hh_world
    hh_world.start(os.path.join(HH_REPO, "reports", "phase1", "world_trace.json"))
except Exception as exc:
    unreal.log_warning("[HH] world events not started: " + str(exc))

if os.path.exists(_request):
    os.remove(_request)
    os.environ["HH_REPO"] = HH_REPO
    unreal.log("[HH] build request found, running hh_setup.py from " + HH_REPO)
    runpy.run_path(os.path.join(HH_REPO, "unreal", "hh_setup.py"), run_name="__main__")

'''


def enable_plugins(uproject):
    with open(uproject, encoding="utf-8-sig") as f:
        data = json.load(f)
    plugins = data.setdefault("Plugins", [])
    for name in PLUGINS:
        entry = next((p for p in plugins if p.get("Name") == name), None)
        if entry:
            entry["Enabled"] = True
        else:
            plugins.append({"Name": name, "Enabled": True})
    with open(uproject, "w", encoding="utf-8") as f:
        json.dump(data, f, indent="\t")
    print(f"[HH] plugins enabled: {', '.join(PLUGINS)}")


def set_ini_keys(ini, section, keys):
    """Set key=value lines inside [section] of an Unreal ini file, keeping everything else."""
    text = open(ini, encoding="utf-8-sig").read() if os.path.exists(ini) else ""
    if section in text:
        start = text.index(section) + len(section)
        nxt = text.find("\n[", start)
        end = len(text) if nxt == -1 else nxt
        body = text[start:end]
        for k, v in keys.items():
            if re.search(rf"^{k}=", body, flags=re.M):
                body = re.sub(rf"^{k}=.*$", f"{k}={v}", body, flags=re.M)
            else:
                body = body.rstrip("\n") + f"\n{k}={v}\n"
        text = text[:start] + body + text[end:]
    else:
        text = text.rstrip("\n") + f"\n\n{section}\n" + "".join(f"{k}={v}\n" for k, v in keys.items())
    os.makedirs(os.path.dirname(ini), exist_ok=True)
    with open(ini, "w", encoding="utf-8") as f:
        f.write(text)


def set_startup_map(project_dir):
    ini = os.path.join(project_dir, "Config", "DefaultEngine.ini")
    set_ini_keys(ini, "[/Script/EngineSettings.GameMapsSettings]", {"EditorStartupMap": MAP, "GameDefaultMap": MAP})
    print(f"[HH] startup map -> {MAP}")


def set_navigation(project_dir):
    # enemies need a nav mesh; Dynamic builds it at runtime too, so Play works even
    # if the editor had not finished building it before the level was saved
    ini = os.path.join(project_dir, "Config", "DefaultEngine.ini")
    set_ini_keys(ini, "[/Script/NavigationSystem.RecastNavMesh]", {"RuntimeGeneration": "Dynamic"})
    print("[HH] nav mesh -> built at runtime (Dynamic)")


# Lumen and virtual shadow maps are far too heavy for integrated graphics: with the
# Paragon heroes on screen single frames took 0.4 s, which made every fight stutter.
# The ship is lit by its own lamps, so plain dynamic lighting looks nearly the same.
RENDERER = {
    "r.DynamicGlobalIlluminationMethod": "0",  # no Lumen GI
    "r.ReflectionMethod": "2",                  # screen-space reflections instead of Lumen
    "r.Shadow.Virtual.Enable": "0",             # regular shadow maps
    "r.GenerateMeshDistanceFields": "False",    # only Lumen needed them
}
# Engine scalability "Medium" for the editor viewport and Play (0 low .. 3 epic)
SCALABILITY = {f"sg.{k}": v for k, v in {
    "ResolutionQuality": "100", "ViewDistanceQuality": "1", "AntiAliasingQuality": "1", "ShadowQuality": "1",
    "GlobalIlluminationQuality": "1", "ReflectionQuality": "1", "PostProcessQuality": "1", "TextureQuality": "2",
    "EffectsQuality": "1", "FoliageQuality": "1", "ShadingQuality": "1", "LandscapeQuality": "1"}.items()}


def set_performance(project_dir):
    set_ini_keys(os.path.join(project_dir, "Config", "DefaultEngine.ini"), "[/Script/Engine.RendererSettings]", RENDERER)
    saved = os.path.join(project_dir, "Saved", "Config", "WindowsEditor")
    for name in ("EditorSettings.ini", "GameUserSettings.ini"):
        set_ini_keys(os.path.join(saved, name), "[ScalabilityGroups]", SCALABILITY)
    print("[HH] performance -> no Lumen / virtual shadows, scalability Medium")


def set_texture_budget(project_dir):
    # the Paragon heroes overflow the default texture pool on integrated graphics
    # ("TEXTURE STREAMING POOL OVER ... BUDGET", blurry textures)
    ini = os.path.join(project_dir, "Config", "DefaultEngine.ini")
    set_ini_keys(ini, "[SystemSettings]", {"r.Streaming.PoolSize": "1500"})
    print("[HH] texture streaming pool -> 1500 MB")


def set_animation(project_dir):
    # 2026-10-11n switched all Control Rig execution off to stop the mannequin foot IK
    # bending the Paragon legs; that froze the heroes in a broken pose instead (legs
    # folded, gun on the floor). Execution is back on; the foot IK node is turned off
    # inside each hero's anim blueprint by hh_combat.disable_foot_ik.
    ini = os.path.join(project_dir, "Config", "DefaultEngine.ini")
    set_ini_keys(ini, "[SystemSettings]", {"ControlRig.DisableExecutionAll": "0"})
    print("[HH] Control Rig -> on (foot IK is switched off per hero instead)")


def install_startup_hook(project_dir, repo):
    path = os.path.join(project_dir, "Content", "Python", "init_unreal.py")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(INIT_UNREAL.format(repo=os.path.abspath(repo)))
    print(f"[HH] startup hook -> {path}")


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--existing", required=True, help="path to the launcher-made .uproject")
    ap.add_argument("--repo", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    help="the hollow-hull folder (default: the one this script is in)")
    args = ap.parse_args(argv)
    if not os.path.isfile(args.existing):
        raise SystemExit(f"no project at {args.existing}; create it in the Unreal launcher first")
    project_dir = os.path.dirname(os.path.abspath(args.existing))
    enable_plugins(args.existing)
    set_startup_map(project_dir)
    set_navigation(project_dir)
    set_texture_budget(project_dir)
    set_performance(project_dir)
    set_animation(project_dir)
    install_startup_hook(project_dir, args.repo)
    print(f"[HH] project ready: {os.path.abspath(args.existing)}")


if __name__ == "__main__":
    main(sys.argv[1:])
